export function getArticlesByCategory(category?: LibraryCategory): MedicalArticle[] {
  if (!category) return MEDICAL_ARTICLES;
  return MEDICAL_ARTICLES.filter(a => a.category === category);
}

export function searchMedicalArticles(query: string): MedicalArticle[] {
  const q = query.toLowerCase().trim();
  if (!q) return MEDICAL_ARTICLES;
  return MEDICAL_ARTICLES.filter(a => 
    a.title.toLowerCase().includes(q) ||
    a.summary.toLowerCase().includes(q) ||
    a.categoryLabel.toLowerCase().includes(q) ||
    a.primarySourceName.toLowerCase().includes(q)
  );
}
