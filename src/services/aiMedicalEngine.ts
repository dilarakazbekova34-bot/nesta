export interface TriageRuleResult {
  level: TriageLevel;
  title: string;
  summary: string;
  urgentNotice?: string;
  redFlags: string[];
  homeCareAdvice: string[];
  whenToConsult: string;
  emergencyNumbers?: string[];
}

export function evaluateSymptomTriage(params: {
  ageMonths: number;
  temperature: number;
  symptoms: string[];
  durationDays: number;
  hasRedFlags: boolean;
  redFlagsList?: string[];
}): TriageRuleResult {
  const { ageMonths, temperature, symptoms, durationDays, hasRedFlags, redFlagsList = [] } = params;

  // RED LEVEL CHECK: IMMEDIATE DANGER
  const isEmergencyTemp = (ageMonths < 3 && temperature >= 38.0) || temperature >= 40.0;
  const isSevereRedFlag = hasRedFlags || redFlagsList.length > 0;
  const hasBreathingDifficulty = symptoms.some(s => s.toLowerCase().includes('дыхан') || s.toLowerCase().includes('одышк') || s.toLowerCase().includes('хрип'));
  const hasConvulsions = symptoms.some(s => s.toLowerCase().includes('судорог') || s.toLowerCase().includes('обморок') || s.toLowerCase().includes('сознан'));
  const hasPetechialRash = symptoms.some(s => s.toLowerCase().includes('геморрагическ') || s.toLowerCase().includes('звездчат') || s.toLowerCase().includes('темная сыпь'));

  if (isSevereRedFlag || isEmergencyTemp || hasBreathingDifficulty || hasConvulsions || hasPetechialRash) {
    return {
      level: 'red',
      title: 'КРАСНЫЙ УРОВЕНЬ — Необходима экстренная медицинская помощь',
      summary: 'Обнаружены признаки, требующие немедленного осмотра врачом скорой медицинской помощи. Не ждите планового приема и не пытайтесь купировать состояние домашними средствами.',
      urgentNotice: 'НЕМЕДЛЕННО ВЫЗОВИТЕ СКОРУЮ ПОМОЩЬ ПО НОМЕРАМ 103 ИЛИ 112 (КАЗАХСТАН)',
      redFlags: redFlagsList.length > 0 ? redFlagsList : [
        'Младенец младше 3 месяцев с температурой 38.0°C или выше',
        'Затрудненное или учащенное дыхание (втяжение межреберий, раздувание крыльев носа)',
        'Выраженная вялость, невозможно разбудить, слабый монотонный плач',
        'Сыпь, которая не исчезает при нажатии прозрачным стаканом'
      ],
      homeCareAdvice: [
        'Обеспечьте свободный доступ свежего воздуха, расстегните тесную одежду',
        'Не укутывайте ребенка при ознобе или жаре, не используйте спиртовые или уксусные обтирания (опасно токсическим отравлением!)',
        'При температуре выше 38.5°C до приезда скорой можно дать жаропонижающее на основе парацетамола или ибупрофена строго по весу ребенка',
        'Приготовьте документы малыша (свидетельство о рождении, прививочный паспорт 063/у, последние выписки)'
      ],
      whenToConsult: 'Немедленно! Бригада скорой помощи должна быть вызвана прямо сейчас.',
      emergencyNumbers: ['103 — Скорая медицинская помощь РК', '112 — Единая дежурно-диспетчерская служба']
    };
  }

  // YELLOW LEVEL CHECK: SCHEDULED PEDIATRICIAN VISIT (24-48 HOURS)
  const isModerateTemp = temperature >= 38.2 || (temperature >= 37.8 && durationDays >= 3);
  const isProlongedCough = symptoms.some(s => s.toLowerCase().includes('кашель')) && durationDays >= 4;
  const isEarPain = symptoms.some(s => s.toLowerCase().includes('ухо') || s.toLowerCase().includes('ушко'));
  const isDiarrheaVomiting = symptoms.some(s => s.toLowerCase().includes('рвота') || s.toLowerCase().includes('понос') || s.toLowerCase().includes('жидкий стул'));

  if (isModerateTemp || isProlongedCough || isEarPain || isDiarrheaVomiting || durationDays >= 3) {
    return {
      level: 'yellow',
      title: 'ЖЁЛТЫЙ УРОВЕНЬ — Требуется очная плановая консультация врача',
      summary: 'Состояние требует профессиональной медицинской оценки педиатра в течение ближайших 24–48 часов для назначения корректного лечения и исключения бактериальных осложнений.',
      redFlags: [],
      homeCareAdvice: [
        'Дробное выпаивание небольшими порциями (вода, грудное молоко или солевые растворы для пероральной регидратации)',
        'Поддерживайте оптимальный микроклимат в детской: температура 19–21°C, влажность 50–60%',
        'Промывание носика изотоническим солевым раствором (0.9% NaCl или морская вода) при заложенности',
        'Фиксируйте частоту мочеиспусканий (не менее 4–5 наполненных подгузников в сутки)'
      ],
      whenToConsult: 'Запишитесь на очный прием к педиатру на сегодня или завтра. При ухудшении состояния немедленно переходите к красному алгоритму.'
    };
  }

  // GREEN LEVEL: SAFE OBSERVATION
  return {
    level: 'green',
    title: 'ЗЕЛЁНЫЙ УРОВЕНЬ — Достаточно бережного наблюдения дома',
    summary: 'Симптомы соответствуют легкому течению адаптации, дентации (прорезыванию зубов) или начальному этапу неосложненной респираторной вирусной инфекции. Экстренной опасности нет.',
    redFlags: [],
    homeCareAdvice: [
      'Спокойный режим, максимальный тактильный контакт с мамой и привычный сон',
      'Обильное теплое питье и продолжение грудного или искусственного вскармливания по требованию',
      'Регулярное проветривание комнаты и влажная уборка',
      'Замеряйте температуру 2–3 раза в день и отмечайте динамику в Дневнике здоровья NESTA'
    ],
    whenToConsult: 'Обратитесь к врачу, если температура держится более 3 дней без тенденции к снижению, либо если ребенок отказывается пить жидкость более 6 часов подряд.'
  };
}
